/** Core Bible data model. Shared by the build pipeline and the app. */

import type { BookId } from './books';

/** BBCCCVVV as a number: John 3:16 = 43003016. */
export type VerseId = number;

/** Inclusive; may cross chapters. */
export interface VerseRange {
  start: VerseId;
  end: VerseId;
}

export type TranslationId = 'bsb' | 'kjv' | 'esv';

export interface TranslationMeta {
  id: TranslationId;
  name: string;
  abbreviation: string;
  source: 'bundled' | 'remote';
  /** Shown wherever this translation's text appears. */
  notice?: string;
  noticeUrl?: string;
}

export interface TextInline {
  type: 'text';
  text: string;
  jesus?: true;
  added?: true;
  divineName?: true;
}

export interface VerseInline {
  type: 'verse';
  n: number;
}

export interface NoteInline {
  type: 'note';
  id: string;
}

/**
 * A verse that is not printed in the running text. It keeps its shared
 * address and appears as a faded, tappable number.
 */
export interface OmittedInline {
  type: 'omitted';
  n: number;
  wording: string;
  wordingSource: 'BSB footnote' | 'KJV';
}

/** Editorial brackets added by the app. They are never stored in the text. */
export interface BracketInline {
  type: 'bracket';
  side: 'open' | 'close';
}

export type Inline =
  | TextInline
  | VerseInline
  | NoteInline
  | OmittedInline
  | BracketInline;

export type ParaStyle = 'p' | 'pmo' | 'pc' | 'q1' | 'q2' | 'qr' | 'li1' | 'li2';

export type Block =
  | { type: 'heading'; level: 1 | 2 | 'acrostic'; inline: Inline[] }
  | { type: 'division'; text: string; subtitle?: string }
  | { type: 'parallelRefs'; text: string }
  | { type: 'descriptive'; inline: Inline[] }
  | { type: 'colophon'; inline: Inline[] }
  | { type: 'para'; style: ParaStyle; inline: Inline[] }
  | { type: 'break' };

export interface NoteRun {
  text: string;
  /** Alternate wording quoted by the note; shown in italics. */
  quote?: true;
  /** A verse number inside the note. */
  verse?: true;
}

export interface Note {
  id: string;
  anchor: VerseId;
  text: NoteRun[];
  /** 'app' marks a note added by Margins, which is not part of the translation. */
  origin?: 'app';
}

export interface ChapterDoc {
  translation: TranslationId;
  book: BookId;
  chapter: number;
  /** Verse numbers printed in this chapter, in order. */
  verses: number[];
  blocks: Block[];
  notes: Note[];
}

/** One generated file: public/bibles/<translation>/<book>.json */
export interface BookFile {
  translation: TranslationId;
  book: BookId;
  chapters: ChapterDoc[];
}

/** Position of one displayed page. index/total count pages within a chapter. */
export interface PageRef {
  range: VerseRange;
  index: number;
  total: number;
}

export type FallbackReason = 'offline' | 'rate-limited' | 'over-limit';

export type ReadResult =
  | { status: 'ok'; doc: ChapterDoc; page: PageRef }
  | {
      status: 'fallback';
      doc: ChapterDoc;
      page: PageRef;
      reason: FallbackReason;
      notice: string;
    };

export interface TranslationProvider {
  meta: TranslationMeta;
  /** The page holding a verse. A translation without the verse returns the page where it would sit. */
  pageFor(verse: VerseId): PageRef;
  read(page: PageRef): Promise<ReadResult>;
}

export interface VariantPassage {
  range: VerseRange;
  appliesTo: TranslationId[];
  bracketed: boolean;
  noteId: string;
}

/** Generated from the BSB by the data pipeline. */
export interface ManuscriptData {
  /** Omitted verse id -> wording taken from the BSB footnote. */
  omitted: Record<string, string>;
  /** Variant note id -> the BSB's own footnote wording. */
  variantNotes: Record<string, NoteRun[]>;
}

/** Generated by the data pipeline. */
export interface VerseIndexData {
  /** Highest verse number in each chapter, across all translations. */
  maxVerse: Record<string, number[]>;
  /** Verse ids a translation lacks, against the shared address list. */
  absent: Partial<Record<TranslationId, VerseId[]>>;
}
